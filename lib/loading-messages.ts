// 코스를 만드는 15~25초 동안 화면이 하는 말.
//
// 🔴 2026-09-04 피드백: 멘트가 4개 고정이라 두 번만 써 보면 다 외워진다.
//    기다림 자체는 줄일 수 없으니(Gemini 호출 + TourAPI 후보 수집), 기다리는
//    동안의 **말**이라도 매번 달라야 한다. 사람이 옆에서 거들어 주는 느낌.
//
// 규칙 두 가지:
//  1. 거짓말하지 않는다 — 실제로 하는 일(동선·영업시간·날씨·기운)만 말한다.
//  2. 「거의 다 됐어요」는 셔플하지 않는다. 시작하자마자 나오면 그게 거짓말이다.

import { shuffle, type Rng } from './random-pick';

/** 순서가 섞이는 본편. 어느 것이 먼저 나와도 말이 되는 문장들만 둔다. */
export const LOADING_MESSAGES: readonly string[] = [
  '당신의 선택에 따라 이모추가 열심히 코스를 짜고 있어요!',
  '이번엔 이렇게 가보는 건 어떨까요?',
  '당신의 기운이 여길 추천하고 있는 것 같네요! 알아보기 쉽게 만들어 드릴게요',
  '지도를 펼쳐놓고 동선을 그려보는 중이에요',
  '이 근처에서 제일 볼만한 곳부터 줄을 세우고 있어요',
  '점심은 어디서 먹을지가 제일 고민이네요...',
  '비 소식까지 확인하고 있어요. 우산은 대신 못 챙겨드리지만요',
  '한국관광공사 데이터를 한 장씩 넘겨보는 중이에요',
  '너무 멀리 떨어진 곳은 빼고 있어요. 이동만 하다 끝나면 아쉬우니까요',
  '그날 문을 여는 곳인지 하나씩 확인하는 중이에요',
  '사진만 예쁜 곳 말고, 실제로 좋았다는 곳으로 고르고 있어요',
  '중간에 커피 한 잔 마실 자리도 넣어드릴게요',
  '기운이 닿는 방향으로 코스를 한 번 돌려보는 중이에요',
  '당신이랑 잘 맞을 것 같은 곳만 남기고 있어요',
];

/** 항상 마지막. 「거의 다」라는 말은 정말 거의 다 됐을 때만 쓴다. */
export const FINAL_LOADING_MESSAGE = '거의 다 됐어요. 순서만 마지막으로 다듬을게요';

/**
 * 첫 화면. 셔플 결과와 무관하게 여기서 시작한다 — 첫 인사는 고정인 편이 낫다.
 * 🔴 LOADING_MESSAGES 안에 있는 문장과 **같은 문자열**이어야 한다.
 *    buildLoadingSequence 가 이 값으로 본편에서 걸러내기 때문에, 다른 문장을 쓰면
 *    거의 같은 말이 6초 간격으로 두 번 나온다.
 */
export const FIRST_LOADING_MESSAGE = LOADING_MESSAGES[0];

/**
 * 이번 생성에 쓸 멘트 순서. 매 호출마다 다르다.
 * 실제로는 6초마다 넘어가니 3~4개만 노출되는데, 그 3~4개가 매번 다른 조합이 된다.
 */
export function buildLoadingSequence(rng: Rng = Math.random): string[] {
  const body = shuffle(LOADING_MESSAGES, rng).filter((m) => m !== FIRST_LOADING_MESSAGE);
  return [FIRST_LOADING_MESSAGE, ...body, FINAL_LOADING_MESSAGE];
}
